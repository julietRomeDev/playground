package class1;

public class Exercise40 {
	//Compare if two numbers are equals.
	public static void main(String[] args) {
		
		int a = 20, i = 19;
		String areEquals = "";

		if(a == i) {
			areEquals = "TRUE";
			System.out.println(areEquals);
		}else if (a != i) {
			areEquals = "FALSE";
			System.out.println(areEquals);
		}

	}
}