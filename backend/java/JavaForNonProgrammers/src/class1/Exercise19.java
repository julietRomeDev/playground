package class1;

public class Exercise19 {

	// Declare a variable named number, initialize with 17
	//Then, apply the 3% using %=

	public static void main(String[] args) {
		int number = 17;
		System.out.println("Original number: " + number);
		number %= 3;
		System.out.println("Percentage: " + number);
	}
}