package class1;

public class Exercise41 {

	//Determinate if a number is pair using %
	public static void main(String[] args) {
		int a = 4;
		String isPair = "";
		if(a % 2==0) {
			isPair = "PAIR";
			System.out.println(isPair);
		}else{
			isPair = "NOT PAIR";
			System.out.println(isPair);
		}
		

	}
}