package class1;

public class Exercise15 {

	// Create a variable named number with value 10, and increase by 5 using +=

	public static void main(String[] args) {
		
		int number = 10;
		System.out.println("Don't increased number: " + number);
		number += 5;
		System.out.println("Increased number: " + number);
	}
}